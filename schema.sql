-- 14. Create Secure Reset Stored Function (SECURITY DEFINER allows bypassing direct table deletes)
CREATE OR REPLACE FUNCTION reset_sistema_autorizado(admin_dni TEXT)
RETURNS VOID AS $$
DECLARE
    is_authorized BOOLEAN;
BEGIN
    -- Validate DNI against secure database table
    SELECT EXISTS(
        SELECT 1 FROM administradores WHERE dni = admin_dni
    ) INTO is_authorized;

    IF NOT is_authorized THEN
        RAISE EXCEPTION 'Operación cancelada: El DNI ingresado no está autorizado.';
    END IF;

    -- Insert into reset log
    INSERT INTO historial_resets (dni) VALUES (admin_dni);

    -- Delete movements and products safely (WHERE clause satisfies safeupdate rules)
    DELETE FROM movimientos WHERE id IS NOT NULL;
    DELETE FROM productos WHERE codigo IS NOT NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
