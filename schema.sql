-- RPC to delete a user account from Auth and Administradores
CREATE OR REPLACE FUNCTION eliminar_usuario_sistema(p_user_id UUID)
RETURNS VOID AS $$
DECLARE
    v_email TEXT;
BEGIN
    SELECT email INTO v_email FROM auth.users WHERE id = p_user_id;
    
