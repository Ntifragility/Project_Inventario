-- 9. Create Secure Policies for Authenticated Users (blocking anonymous public CRUD)
DROP POLICY IF EXISTS "Allow anonymous access on unidades" ON unidades;
DROP POLICY IF EXISTS "Allow authenticated access on unidades" ON unidades;
CREATE POLICY "Allow authenticated access on unidades" ON unidades FOR ALL TO authenticated USING (true) WITH CHECK (true);

