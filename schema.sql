        DELETE FROM administradores WHERE LOWER(email) = LOWER(v_email);
    END IF;
    
    DELETE FROM auth.users WHERE id = p_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- RPC to fetch system audit logs joined with user emails
CREATE OR REPLACE FUNCTION obtener_logs_auditoria()
RETURNS TABLE (
    id BIGINT,
    tabla VARCHAR,
    operacion VARCHAR,
    registro_id TEXT,
    datos_anteriores JSONB,
    datos_nuevos JSONB,
    fecha TIMESTAMPTZ,
    usuario_email TEXT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        a.id,
        a.tabla::VARCHAR,
        a.operacion::VARCHAR,
        a.registro_id,
        a.datos_anteriores,
        a.datos_nuevos,
        a.fecha,
        COALESCE(u.email, 'Sistema/Anónimo')::TEXT AS usuario_email
    FROM audit_log a
    LEFT JOIN auth.users u ON a.usuario_id = u.id
    ORDER BY a.fecha DESC
    LIMIT 100;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- 1. Create the security backups table
CREATE TABLE IF NOT EXISTS respaldos_seguridad (
    id SERIAL PRIMARY KEY,
    fecha TIMESTAMPTZ DEFAULT NOW(),
    creado_por TEXT DEFAULT 'Sistema (Automático)',
    productos_snapshot JSONB NOT NULL,
    movimientos_snapshot JSONB NOT NULL
);

-- Enable RLS on backing table
ALTER TABLE respaldos_seguridad ENABLE ROW LEVEL SECURITY;

-- Allow only authenticated administrators to select backups
DROP POLICY IF EXISTS "respaldos_select_policy" ON respaldos_seguridad;
CREATE POLICY "respaldos_select_policy" ON respaldos_seguridad 
    FOR SELECT TO authenticated 
    USING (EXISTS (SELECT 1 FROM administradores WHERE LOWER(email) = LOWER(auth.jwt() ->> 'email')));

-- 2. Create the snapshot function
CREATE OR REPLACE FUNCTION crear_respaldo_seguridad(p_creado_por TEXT DEFAULT 'Sistema (Automático)')
RETURNS VOID AS $$
DECLARE
    v_prod_json JSONB;
    v_mov_json JSONB;
BEGIN
    -- Capture snapshots as JSONB arrays
    SELECT COALESCE(jsonb_agg(p), '[]'::jsonb) INTO v_prod_json FROM v_productos_stock p;
    SELECT COALESCE(jsonb_agg(m), '[]'::jsonb) INTO v_mov_json FROM movimientos m;

    INSERT INTO respaldos_seguridad (creado_por, productos_snapshot, movimientos_snapshot)
    VALUES (p_creado_por, v_prod_json, v_mov_json);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 3. Enable pg_cron and schedule it weekly on Sunday at midnight (00:00)
CREATE EXTENSION IF NOT EXISTS pg_cron;
SELECT cron.schedule('weekly-inventory-backup', '0 0 * * 0', 'SELECT crear_respaldo_seguridad()');


-- RPC to list backups (SECURITY DEFINER)
CREATE OR REPLACE FUNCTION listar_respaldos_seguridad(p_email TEXT)
RETURNS TABLE (
    id INT,
    fecha TIMESTAMPTZ,
    creado_por TEXT
) AS $$
DECLARE
    is_admin BOOLEAN;
BEGIN
    SELECT EXISTS(
        SELECT 1 FROM public.administradores WHERE LOWER(email) = LOWER(p_email)
    ) INTO is_admin;

    IF NOT is_admin THEN
        RAISE EXCEPTION 'Acceso denegado: El usuario no es administrador.';
    END IF;

    RETURN QUERY
    SELECT r.id, r.fecha, r.creado_por 
    FROM public.respaldos_seguridad r
    ORDER BY r.fecha DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- RPC to fetch backup snapshots (SECURITY DEFINER)
CREATE OR REPLACE FUNCTION obtener_respaldo_seguridad_detalle(p_email TEXT, p_respaldo_id INT)
RETURNS TABLE (
    productos_snapshot JSONB,
    movimientos_snapshot JSONB
) AS $$
DECLARE
    is_admin BOOLEAN;
BEGIN
    SELECT EXISTS(
        SELECT 1 FROM public.administradores WHERE LOWER(email) = LOWER(p_email)
    ) INTO is_admin;

    IF NOT is_admin THEN
        RAISE EXCEPTION 'Acceso denegado: El usuario no es administrador.';
    END IF;

    RETURN QUERY
    SELECT r.productos_snapshot, r.movimientos_snapshot 
    FROM public.respaldos_seguridad r
    WHERE r.id = p_respaldo_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


