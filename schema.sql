-- RPC to list all authentication users with their admin status
CREATE OR REPLACE FUNCTION listar_usuarios_sistema()
RETURNS TABLE (
    id UUID,
    email VARCHAR,
    created_at TIMESTAMPTZ,
    last_sign_in_at TIMESTAMPTZ,
    es_admin BOOLEAN,
    admin_dni VARCHAR,
    admin_nombre VARCHAR
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        u.id,
        u.email::VARCHAR,
        u.created_at,
        u.last_sign_in_at,
        (a.dni IS NOT NULL) AS es_admin,
        a.dni::VARCHAR AS admin_dni,
        a.nombre::VARCHAR AS admin_nombre
    FROM auth.users u
    LEFT JOIN administradores a ON LOWER(u.email) = LOWER(a.email)
    ORDER BY u.created_at DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


