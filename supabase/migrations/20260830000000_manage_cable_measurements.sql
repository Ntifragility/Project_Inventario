CREATE OR REPLACE VIEW public.v_cable_dashboard AS
SELECT
    cs.tag_unico,
    cs.wbs,
    cs.plano,
    cs.area,
    cs.servicio,
    cs.tipo_cable,
    cs.tipo_servicio,
    cs.total_estimado_m,
    cs.metrado_reportado_campo,
    cs.conexion_origen,
    cs.conexion_destino,
    cs.estado,
    cs.total_estimado_m - cs.metrado_reportado_campo AS longitud_pendiente_m,
    CASE WHEN cs.metrado_reportado_campo >= cs.total_estimado_m AND cs.total_estimado_m > 0
         THEN TRUE ELSE FALSE END AS is_tendido,
    COALESCE(cs.despachado_override_m, d.total_despachado, 0) AS total_despachado_m,
    COALESCE(d.num_despachos, 0) AS num_despachos
FROM public.cable_schedule cs
LEFT JOIN (
    SELECT cable_schedule_id,
           SUM(longitud_despachada_m) AS total_despachado,
           COUNT(*) AS num_despachos
    FROM public.cable_despachos
    GROUP BY cable_schedule_id
) d ON d.cable_schedule_id = cs.id;

