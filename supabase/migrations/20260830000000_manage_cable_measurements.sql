CREATE OR REPLACE FUNCTION public.current_project_role_for_area(p_project_area_id UUID)
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT pm.role
    FROM public.project_areas pa
    JOIN public.project_memberships pm
      ON pm.project_id = pa.project_id
     AND pm.user_id = auth.uid()
    WHERE pa.id = p_project_area_id
      AND pm.role IN ('admin', 'supervisor', 'user')
    LIMIT 1;
$$;

