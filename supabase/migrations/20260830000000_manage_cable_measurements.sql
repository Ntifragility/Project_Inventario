CREATE OR REPLACE FUNCTION public.audit_cable_measurement_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_role TEXT;
    v_dispatch_sum NUMERIC(12, 2);
    v_old_dispatch NUMERIC(12, 2);
    v_new_dispatch NUMERIC(12, 2);
    v_source TEXT := COALESCE(NULLIF(current_setting('app.cable_measurement_source', TRUE), ''), 'DATABASE');
    v_reason TEXT := NULLIF(current_setting('app.cable_measurement_reason', TRUE), '');
BEGIN
    v_role := public.current_project_role_for_area(NEW.project_area_id);

    IF NEW.total_estimado_m IS DISTINCT FROM OLD.total_estimado_m THEN
        IF v_role IS DISTINCT FROM 'admin' THEN
            RAISE EXCEPTION 'Solo un administrador puede modificar METRADO OT.';
        END IF;
        IF NEW.total_estimado_m IS NULL OR NEW.total_estimado_m < 0 THEN
            RAISE EXCEPTION 'METRADO OT debe ser un numero mayor o igual a cero.';
        END IF;

        INSERT INTO public.cable_measurement_changes (
            project_area_id, cable_schedule_id, tag_unico_snapshot,
            wbs_snapshot, sistema_snapshot, field_name,
            old_value, new_value, changed_by, changed_by_role, source, reason
        ) VALUES (
            NEW.project_area_id, NEW.id, NEW.tag_unico,
            NEW.wbs, NEW.sistema, 'METRADO_OT',
            COALESCE(OLD.total_estimado_m, 0), COALESCE(NEW.total_estimado_m, 0),
            auth.uid(), v_role, v_source, v_reason
        );
    END IF;

    IF NEW.despachado_override_m IS DISTINCT FROM OLD.despachado_override_m THEN
        IF v_role IS NULL OR NOT public.can_access_project_area(NEW.project_area_id) THEN
            RAISE EXCEPTION 'No tiene permisos para modificar METRADO DESPACHADO en esta area.';
        END IF;

        SELECT COALESCE(SUM(cd.longitud_despachada_m), 0)
        INTO v_dispatch_sum
        FROM public.cable_despachos cd
        WHERE cd.cable_schedule_id = NEW.id;

        v_old_dispatch := COALESCE(OLD.despachado_override_m, v_dispatch_sum, 0);
        v_new_dispatch := COALESCE(NEW.despachado_override_m, v_dispatch_sum, 0);

        INSERT INTO public.cable_measurement_changes (
            project_area_id, cable_schedule_id, tag_unico_snapshot,
            wbs_snapshot, sistema_snapshot, field_name,
            old_value, new_value, changed_by, changed_by_role, source, reason
        ) VALUES (
            NEW.project_area_id, NEW.id, NEW.tag_unico,
            NEW.wbs, NEW.sistema, 'METRADO_DESPACHADO',
            v_old_dispatch, v_new_dispatch,
            auth.uid(), v_role, v_source, v_reason
        );
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS audit_cable_measurements ON public.cable_schedule;
CREATE TRIGGER audit_cable_measurements
    BEFORE UPDATE OF total_estimado_m, despachado_override_m
    ON public.cable_schedule
    FOR EACH ROW
    EXECUTE FUNCTION public.audit_cable_measurement_change();

CREATE OR REPLACE FUNCTION public.actualizar_metrado_ot_cable(
    p_cable_id BIGINT,
    p_project_area_id UUID,
    p_expected_old_value NUMERIC,
    p_new_value NUMERIC,
    p_reason TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_row public.cable_schedule%ROWTYPE;
BEGIN
    IF NOT public.can_admin_project_area(p_project_area_id) THEN
        RAISE EXCEPTION 'Solo un administrador puede modificar METRADO OT.';
    END IF;
    IF p_new_value IS NULL OR p_new_value < 0 THEN
        RAISE EXCEPTION 'METRADO OT debe ser un numero mayor o igual a cero.';
    END IF;

    SELECT * INTO v_row
    FROM public.cable_schedule
    WHERE id = p_cable_id AND project_area_id = p_project_area_id
    FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'El cable no existe en el area activa.'; END IF;
    IF COALESCE(v_row.total_estimado_m, 0) IS DISTINCT FROM ROUND(p_expected_old_value, 2) THEN
        RAISE EXCEPTION 'METRADO OT fue modificado por otro usuario. Actualice la tabla e intente nuevamente.';
    END IF;

    PERFORM set_config('app.cable_measurement_source', 'DETALLE_CIRCUITOS', TRUE);
    PERFORM set_config('app.cable_measurement_reason', COALESCE(BTRIM(p_reason), ''), TRUE);

    UPDATE public.cable_schedule
    SET total_estimado_m = ROUND(p_new_value, 2), updated_at = NOW()
    WHERE id = p_cable_id;

    RETURN jsonb_build_object('id', p_cable_id, 'field', 'METRADO_OT', 'value', ROUND(p_new_value, 2));
END;
$$;

