CREATE OR REPLACE FUNCTION public.exportar_cambios_metrado_cable(
    p_project_area_id UUID,
    p_start_date DATE,
    p_end_date DATE
)
RETURNS TABLE (
    changed_at TIMESTAMPTZ,
    area_name TEXT,
    tag_unico TEXT,
    wbs TEXT,
    sistema TEXT,
    field_name TEXT,
    old_value NUMERIC,
    new_value NUMERIC,
    difference NUMERIC,
    changed_by UUID,
    changed_by_name TEXT,
    changed_by_role TEXT,
    source TEXT,
    reason TEXT
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF p_start_date IS NULL OR p_end_date IS NULL OR p_end_date < p_start_date THEN
        RAISE EXCEPTION 'Seleccione un rango de fechas valido.';
    END IF;
    IF NOT public.can_access_project_area(p_project_area_id) THEN
        RAISE EXCEPTION 'No tiene acceso al area seleccionada.';
    END IF;

    RETURN QUERY
    SELECT
        c.changed_at,
        pa.name::TEXT,
        c.tag_unico_snapshot::TEXT,
        c.wbs_snapshot::TEXT,
        c.sistema_snapshot::TEXT,
        c.field_name,
        c.old_value,
        c.new_value,
        c.new_value - c.old_value,
        c.changed_by,
        COALESCE(up.display_name, c.changed_by::TEXT)::TEXT,
        c.changed_by_role,
        c.source,
        c.reason
    FROM public.cable_measurement_changes c
    JOIN public.project_areas pa ON pa.id = c.project_area_id
    LEFT JOIN public.user_profiles up ON up.user_id = c.changed_by
    WHERE c.project_area_id = p_project_area_id
      AND c.changed_at >= (p_start_date::TIMESTAMP AT TIME ZONE 'America/Lima')
      AND c.changed_at < ((p_end_date + 1)::TIMESTAMP AT TIME ZONE 'America/Lima')
    ORDER BY c.changed_at, c.id;
END;
$$;

